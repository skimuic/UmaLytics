// Regenerates the Uma tables from the drafter's own web bundle. Run by hand
// when a new Uma releases (pnpm sync:umas); never at extension runtime or in CI.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ORIGIN = 'https://drafter.uma.guide';
const root = fileURLToPath(new URL('../', import.meta.url));
const umasDir = path.join(root, 'apps', 'extension', 'umas');

const STRING = '"(?:[^"\\\\]|\\\\.)*"';
const RELEASE_ENTRY = `\\{name:(${STRING}),variant:(${STRING}),outfitId:"(\\d{6})"\\}`;
const RELEASE_ARRAY = new RegExp(`\\[${RELEASE_ENTRY}(?:,${RELEASE_ENTRY})*\\]`, 'g');
const PORTRAIT_MAP = /\{\d{6}:\d{6}(?:,\d{6}:\d{6})*\}/g;

// A match this small is some unrelated literal, not the drafter's table.
const MIN_RELEASE_ENTRIES = 100;
const MIN_PORTRAIT_ENTRIES = 50;

function fail(message) {
  console.error(`sync-uma-data: ${message}`);
  process.exit(1);
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) fail(`GET ${url} failed with HTTP ${response.status}.`);
  return response.text();
}

function readReleaseOrder(bundle) {
  const entryPattern = new RegExp(RELEASE_ENTRY, 'g');
  let best = [];
  for (const [literal] of bundle.matchAll(RELEASE_ARRAY)) {
    const entries = [...literal.matchAll(entryPattern)].map(([, name, variant, outfitId]) => (
      { name: JSON.parse(name), variant: JSON.parse(variant), outfitId }
    ));
    if (entries.length > best.length) best = entries;
  }
  if (best.length < MIN_RELEASE_ENTRIES) {
    fail('could not find the release-order array ([{name,variant,outfitId}, ...]) in the drafter bundle. The bundle format has changed; update scripts/sync-uma-data.mjs.');
  }
  const duplicate = best.find((entry, index) => best.findIndex(other => other.outfitId === entry.outfitId) !== index);
  if (duplicate) fail(`release order lists outfit ${duplicate.outfitId} more than once.`);
  return best;
}

function readPortraitMap(bundle, outfitIds) {
  let best = [];
  for (const [literal] of bundle.matchAll(PORTRAIT_MAP)) {
    const pairs = literal.slice(1, -1).split(',').map(pair => pair.split(':'));
    if (pairs.length > best.length) best = pairs;
  }
  if (best.length < MIN_PORTRAIT_ENTRIES) {
    fail('could not find the outfit-to-portrait map ({100102:100130, ...}) in the drafter bundle. The bundle format has changed; update scripts/sync-uma-data.mjs.');
  }
  const unknown = best.filter(([outfitId]) => !outfitIds.has(outfitId));
  if (unknown.length > 0) {
    fail(`portrait map lists outfits missing from the release order: ${unknown.map(([outfitId]) => outfitId).join(', ')}.`);
  }
  return best;
}

function releaseOrderSource(entries) {
  return `// Release order from NEWEST (index 0) to OLDEST
// This list follows JP release order, Global follows the same order
// outfitId maps to jpumas.json outfit IDs for accurate matching
// Generated by scripts/sync-uma-data.mjs from ${ORIGIN} - do not edit.

export interface ReleaseEntry {
  name: string;
  variant: string;
  outfitId: string;
}

export const releaseOrder: ReleaseEntry[] = [
${entries.map(({ name, variant, outfitId }) => (
    `  { name: ${JSON.stringify(name)}, variant: ${JSON.stringify(variant)}, outfitId: ${JSON.stringify(outfitId)} }`
  )).join(',\n')}
];
`;
}

function portraitMapSource(pairs) {
  return `// Generated by scripts/sync-uma-data.mjs from ${ORIGIN} - do not edit.

export const UMA_PORTRAIT_ID_BY_OUTFIT_ID = new Map<string, string>([
${pairs.map(([outfitId, portraitId]) => `  ['${outfitId}', '${portraitId}']`).join(',\n')}
]);
`;
}

const html = await fetchText(`${ORIGIN}/`);
const scriptPath = /\/assets\/index-[\w-]+\.js/.exec(html)?.[0];
if (!scriptPath) fail(`no /assets/index-*.js bundle is referenced by ${ORIGIN}/.`);

const bundle = await fetchText(`${ORIGIN}${scriptPath}`);
const releaseOrder = readReleaseOrder(bundle);
const portraitPairs = readPortraitMap(bundle, new Set(releaseOrder.map(entry => entry.outfitId)));

fs.writeFileSync(path.join(umasDir, 'umaReleaseOrder.ts'), releaseOrderSource(releaseOrder));
fs.writeFileSync(path.join(umasDir, 'umaPortraitMap.ts'), portraitMapSource(portraitPairs));
console.log(`sync-uma-data: ${scriptPath}: ${releaseOrder.length} release entries, ${portraitPairs.length} portrait overrides.`);
